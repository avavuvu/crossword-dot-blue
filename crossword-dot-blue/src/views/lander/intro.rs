use maud::{Markup, html};

const FIRST_SLOT_MS: f64 = 50.0;
const LAST_SLOT_MS: f64 = 190.0;

const VIEWBOX_X: f64 = -130.0;
const VIEWBOX_WIDTH: f64 = 1400.0;
const WORDMARK_LEFT: f64 = 792.48;
const WORDMARK_RIGHT: f64 = 1114.24;
const WORDMARK_BASELINE: f64 = 121.46;

fn wordmark_center() -> f64 {
    (WORDMARK_LEFT + WORDMARK_RIGHT) / 2.0
}

fn center_shift() -> f64 {
    VIEWBOX_X + VIEWBOX_WIDTH / 2.0 - wordmark_center()
}

fn slot_ms(index: usize, count: usize) -> f64 {
    let progress = index as f64 / count.saturating_sub(1).max(1) as f64;
    FIRST_SLOT_MS + (LAST_SLOT_MS - FIRST_SLOT_MS) * progress * progress
}

fn slots(count: usize) -> (Vec<(f64, f64)>, f64) {
    let mut start = 0.0;
    let slots = (0..count)
        .map(|index| {
            let slot = slot_ms(index, count);
            let entry = (start, slot);
            start += slot;
            entry
        })
        .collect();
    (slots, start)
}

